#!/usr/bin/env python3
"""Generate one TeX-safe macro per numeric snapshot entry (no derived values).

Numeric key components become spelled digits: g7 -> GSeven, 02 -> ZeroTwo.
This avoids digits in TeX control words. Universal schemas without a value have
no numeric macro. Every macro is safe inside or outside math via ensuremath.
"""
import argparse
from fractions import Fraction
import json
from pathlib import Path
import re
import sys

PAPER = Path(__file__).resolve().parents[1]
SNAPSHOT = PAPER / 'data/current_results.json'
OUTPUT = PAPER / 'figures/generated/figdata.tex'
DIGITS = ['Zero','One','Two','Three','Four','Five','Six','Seven','Eight','Nine']


def macro_name(key):
    if not re.fullmatch(r'[a-z][a-z0-9_]*', key): raise ValueError(f'Invalid snapshot key: {key}')
    words = [re.sub(r'\d', lambda m: DIGITS[int(m[0])], part[0].upper()+part[1:]) for part in key.split('_')]
    return 'snap' + ''.join(words)


def number_tex(value):
    if not re.fullmatch(r'-?(?:0|[1-9]\d*)(?:/[1-9]\d*)?', value): raise ValueError(f'Invalid exact value: {value}')
    if '/' not in value: return value
    q = Fraction(value)
    if value != f'{q.numerator}/{q.denominator}': raise ValueError(f'Noncanonical rational: {value}')
    return str(q.numerator) if q.denominator == 1 else rf'\frac{{{q.numerator}}}{{{q.denominator}}}'


def macros(snapshot):
    out = []; seen = set()
    for entry in snapshot['entries']:
        name = macro_name(entry['key'])
        if name in seen: raise ValueError(f'Macro-name collision: {name}')
        seen.add(name)
        values = json.loads(entry['value']) if entry['value_type'].endswith('_list') else [entry['value']]
        if not isinstance(values, list) or not all(isinstance(v,str) for v in values): raise ValueError('Expected exact string list')
        out.append((entry['key'],name,', '.join(number_tex(v) for v in values)))
    return out


def render(snapshot):
    lines=['% GENERATED by paper/tools/render_figure_data.py; do not edit.',
           '% Source: paper/data/current_results.json. Numeric entries only; schemas are nonnumeric.',
           '% Key digits are spelled out in TeX control words (g7 -> GSeven, 02 -> ZeroTwo).']
    for key,name,body in macros(snapshot):
        lines += ['% snapshot key: '+key, rf'\newcommand{{\{name}}}{{\ensuremath{{{body}}}}}']
    # Selectors of pinned lists are copied from the same exact snapshot
    # values, never inferred from model prose or typed into figure labels.
    for key,name,body in element_macros(snapshot):
        lines += ['% snapshot list element: '+key,
                  rf'\newcommand{{\{name}}}{{\ensuremath{{{body}}}}}']
    return '\n'.join(lines)+'\n'


def element_macros(snapshot):
    out = []; seen = {name for _,name,_ in macros(snapshot)}
    for entry in snapshot['entries']:
        if not entry['value_type'].endswith('_list'): continue
        for i,value in enumerate(json.loads(entry['value'])):
            # Spelled, zero-based indices ensure valid TeX control words.
            name = macro_name(entry['key']) + 'Item' + ''.join(DIGITS[int(d)] for d in str(i))
            if name in seen: raise ValueError('Macro-name collision: '+name)
            seen.add(name)
            out.append((entry['key']+'['+str(i)+']',name,number_tex(value)))
    return out


def main():
    parser=argparse.ArgumentParser(description=__doc__); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    text=render(json.loads(SNAPSHOT.read_text()))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_bytes()!=text.encode():
            print('Figure-data drift: '+str(OUTPUT),file=sys.stderr); return 1
        print('PASS: figure data matches snapshot'); return 0
    OUTPUT.parent.mkdir(parents=True,exist_ok=True); OUTPUT.write_text(text)
    print('Wrote '+str(OUTPUT)); return 0


if __name__=='__main__': raise SystemExit(main())
